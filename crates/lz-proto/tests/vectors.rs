//! Checks `spec/vectors/v0.json` against this crate, so the published
//! vectors and the code can't drift apart.
//!
//! To regenerate after an intentional change:
//! `LZ_REGEN_VECTORS=1 cargo test -p lz-proto --test vectors`

use lz_proto::api::EventStatus;
use lz_proto::event_id::{Pool, event_id};
use lz_proto::lease::clamp_duration;
use lz_proto::padding::pad_ping_json;
use lz_proto::replay::SeqWindow;
use lz_proto::token::AccountToken;
use lz_proto::webhook::{SECRET_LEN, SigningSecret, sign, webhook_id};
use serde_json::{Value, json};
use sha2::{Digest, Sha256};

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../spec/vectors/v0.json");

fn seq(start: u8, len: usize) -> Vec<u8> {
    (0..len).map(|i| start.wrapping_add(i as u8)).collect()
}

fn generate() -> Value {
    let mut token_bytes = [0u8; 32];
    token_bytes.copy_from_slice(&seq(0, 32));
    let token = AccountToken::from_bytes(token_bytes);
    let text = token.encode();

    let secret = seq(0x80, 32);
    let mut account = [0u8; 16];
    account.copy_from_slice(&seq(0, 16));
    let mut txid = [0u8; 32];
    txid.copy_from_slice(&seq(0x20, 32));
    let ids: Vec<Value> = [
        (Pool::Sapling, 0u32),
        (Pool::Orchard, 0),
        (Pool::Ironwood, 0),
        (Pool::Ironwood, 1),
    ]
    .into_iter()
    .map(|(pool, index)| {
        json!({
            "pool": pool, "index": index,
            "id": event_id(&secret, &account, &txid, pool, index),
        })
    })
    .collect();

    let mut w = SeqWindow::default();
    let replay: Vec<Value> = [10u64, 12, 11, 12, 80, 16, 17, 17, 9]
        .into_iter()
        .map(|s| json!({ "seq": s, "accepted": w.accept(s).is_ok() }))
        .collect();

    let event = &ids[0]["id"].as_str().unwrap().to_owned();
    let states: Vec<Value> = [
        (EventStatus::Mempool, None, 0u32),
        (EventStatus::Mined, Some(3_500_000u64), 1),
        (EventStatus::Mined, Some(3_500_000), 10),
        (EventStatus::Reorged, None, 0),
    ]
    .into_iter()
    .map(|(status, height, confirmations)| {
        json!({
            "status": status, "height": height, "confirmations": confirmations,
            "webhook_id": webhook_id(event, status, height, confirmations),
        })
    })
    .collect();
    let mut secret_bytes = [0u8; SECRET_LEN];
    secret_bytes.copy_from_slice(&seq(0x40, SECRET_LEN));
    let signing = SigningSecret::from_bytes(secret_bytes);
    let signed_id = webhook_id(event, EventStatus::Mined, Some(3_500_000), 1);
    let body = r#"{"id":"example"}"#;

    let ping_json = r#"{"v":0,"t":"wake","events":[]}"#;
    let ping = pad_ping_json(ping_json).unwrap();

    json!({
        "description": "Lantern Zero protocol v0 test vectors. Byte strings are hex. Generated by crates/lz-proto/tests/vectors.rs.",
        "token": {
            "secret_hex": hex::encode(token_bytes),
            "text": text.as_str(),
            "sha256_hex": hex::encode(token.hash().0),
        },
        "event_id": {
            "server_secret_hex": hex::encode(&secret),
            "account_id_hex": hex::encode(account),
            "txid_hex": hex::encode(txid),
            "cases": ids,
        },
        "webhook": {
            "event_id": event,
            "ids": states,
            "secret": signing.encode().as_str(),
            "signature": {
                "webhook_id": signed_id,
                "timestamp": 1_800_000_000u64,
                "body": body,
                "header": sign(&signing, &signed_id, 1_800_000_000, body.as_bytes()),
            },
        },
        "replay_window": { "window": lz_proto::replay::WINDOW, "steps": replay },
        "lease_duration": [
            { "requested": 60, "paid_secs_left": null, "granted": clamp_duration(60, None) },
            { "requested": 604800, "paid_secs_left": null, "granted": clamp_duration(604_800, None) },
            { "requested": 9999999, "paid_secs_left": null, "granted": clamp_duration(9_999_999, None) },
            { "requested": 604800, "paid_secs_left": 3600, "granted": clamp_duration(604_800, Some(3_600)) },
        ],
        "ping": {
            "json": ping_json,
            "padded_len": ping.len(),
            "padded_sha256_hex": hex::encode(Sha256::digest(&ping)),
        },
    })
}

#[test]
fn published_vectors_match_code() {
    let fresh = generate();
    if std::env::var_os("LZ_REGEN_VECTORS").is_some() {
        let mut text = serde_json::to_string_pretty(&fresh).unwrap();
        text.push('\n');
        std::fs::write(PATH, text).unwrap();
        return;
    }
    let published: Value =
        serde_json::from_str(&std::fs::read_to_string(PATH).expect("spec/vectors/v0.json"))
            .expect("valid JSON");
    assert_eq!(
        published, fresh,
        "spec/vectors/v0.json is out of date; see this file's header"
    );
}

/// The published token text must parse back to its secret.
#[test]
fn published_token_parses() {
    if std::env::var_os("LZ_REGEN_VECTORS").is_some() {
        return;
    }
    let v: Value = serde_json::from_str(&std::fs::read_to_string(PATH).unwrap()).unwrap();
    let t = AccountToken::parse(v["token"]["text"].as_str().unwrap()).unwrap();
    assert_eq!(
        hex::encode(t.hash().0),
        v["token"]["sha256_hex"].as_str().unwrap()
    );
}
